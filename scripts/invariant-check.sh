#!/usr/bin/env bash
# Считает, у скольких инвариантов из docs/ARCHITECTURE.md есть тест, а не
# сколько всего *_test.go файлов в репозитории.
#
# Зачем отдельно от reconcile-check.sh: тот проверяет docs/RECONCILIATION.md
# по своему собственному docstring'у, это разные документы и разные вопросы.
#
# Зачем вообще: до этого скрипта ARCHITECTURE.md предлагал измерять покрытие
# командой `git ls-files '*_test.go' | wc -l` — числом файлов с тестами,
# а не тем, что эти тесты проверяют. Число росло с любым тестом (httpx, wsh,
# clock — ни один не про инвариант) и в какой-то момент стало больше нуля,
# хотя ни один из шести инвариантов ещё не был покрыт тестом. Документ говорил
# «инварианты есть», хотя их не было ни одного — тот самый класс дефектов,
# который в этом проекте уже ловили руками («гейт, который ничего не
# проверяет», docs/DECISIONS.md).
#
# Механизм: тест, доказывающий инвариант N, несёт маркер `// invariant:N`
# в комментарии над функцией. grep по всем *_test.go находит маркеры;
# остальное тесты не считаются, сколько бы их ни было.
#
# Запуск: make invariants
set -uo pipefail
cd "$(git rev-parse --show-toplevel)" || exit 1

# Цвет только в терминале — см. scripts/doctor.sh.
if [ -t 1 ] && [ -z "${NO_COLOR:-}" ]; then
  C_OK=$'\033[32m'; C_BAD=$'\033[31m'; C_OFF=$'\033[0m'
else
  C_OK=''; C_BAD=''; C_OFF=''
fi

# Текст инвариантов — дословно из docs/ARCHITECTURE.md → «## Инварианты».
# Своя копия текста здесь означала бы дублирование факта (docs/AGENTS.md,
# класс дефектов «дублирование фактов»), поэтому только номер и краткая метка,
# на случай если кто-то не откроет ARCHITECTURE.md рядом с выводом.
declare -A LABELS=(
  [1]="XP только с записью в лог: idempotency-ключ + суточный кап"
  [2]="награда привязана к пользователю, без пересылаемого кода"
  [3]="source (gamified|organic) не теряется event_inbox → energy_ledger"
  [4]="однократная выдача награды при конкурентных claim'ах"
  [5]="время в домене — параметр, не time.Now() внутри"
  [6]="прогресс пользователя не обнуляется миграцией"
)

covered=0
missing=0

for n in 1 2 3 4 5 6; do
  hits=$(grep -rl "invariant:$n\b" --include='*_test.go' . 2>/dev/null | sort)
  if [ -n "$hits" ]; then
    count=$(printf '%s\n' "$hits" | wc -l)
    printf '  %sDONE%s  инвариант %d — %s (%d файл(ов): %s)\n' \
      "$C_OK" "$C_OFF" "$n" "${LABELS[$n]}" "$count" "$(printf '%s' "$hits" | tr '\n' ' ')"
    covered=$((covered + 1))
  else
    printf '  %sTODO%s  инвариант %d — %s — теста нет\n' "$C_BAD" "$C_OFF" "$n" "${LABELS[$n]}"
    missing=$((missing + 1))
  fi
done

echo
echo "Инвариантов с тестом: $covered из 6, без теста: $missing."
if [ "$missing" -gt 0 ]; then
  echo "«Без теста» — не обязательно баг: часть инвариантов относится к фичам"
  echo "(награды, event_inbox/energy_ledger, миграции), которых в коде может"
  echo "ещё не быть. Разница со старой формулировкой ARCHITECTURE.md в том,"
  echo "что раньше число *_test.go файлов росло от тестов httpx/wsh/clock —"
  echo "ни один из них не про инвариант — и молча читалось как «инварианты"
  echo "есть». Теперь видно, какие именно есть, а какие нет."
fi
exit 0
