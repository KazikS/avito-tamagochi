// Package migrations встраивает SQL-миграции в бинарь.
//
// Зачем встраивать, а не читать каталог с диска: миграции должны накатываться
// одинаково из трёх мест — `make migrate` на машине разработчика, тесты
// (pkg/pgtest) и контейнер, в котором никакого каталога migrations рядом с
// бинарём нет. Встроенная файловая система — единственный источник, который
// одинаков во всех трёх случаях; каталог на диске в контейнере пришлось бы
// копировать отдельным слоем Dockerfile и он молча разъехался бы с бинарём.
//
// Пакет лежит в каталоге с самими .sql, потому что go:embed не умеет
// подниматься выше каталога пакета.
package migrations

import "embed"

// FS — все миграции проекта.
//
//go:embed *.sql
var FS embed.FS
