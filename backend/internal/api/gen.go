// Package api содержит типы, сгенерированные из docs/openapi.json.
//
// Руками здесь ничего не пишут: файл types.gen.go перезаписывается `make gen`,
// а CI-джоб contract-drift падает, если сгенерированное разошлось со спекой.
// Меняешь форму запроса или ответа — правь спеку и перегенерируй.
//
// Генерируются ТОЛЬКО типы, без серверных интерфейсов. Причина: генератор
// gin-server выдал бы ServerInterface на все операции контракта разом, и
// сборка падала бы у любого, кто не реализовал их все — то есть у feat/auth
// и feat/pet-service в момент мержа. Типы такого обязательства не создают.
//
// Версия инструмента запинена прямо в директиве: `go run tool@версия` не
// требует ставить что-либо глобально (репозиторий — гость на чужой машине),
// и, в отличие от линтеров, здесь этот способ работает — кодоген читает JSON,
// а не исходники модуля.
